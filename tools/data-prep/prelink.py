#!/usr/bin/env python3
"""Pre-link the armv7 slice of the iOS binary into a flat image for the Vita loader (ios/vita/loader.c).

Usage: prelink.py <DukeNukemMP binary> <out image> <out imports header>

Image file (little endian, all addresses are unslid vm addresses of the Mach-O):
  header  "DNMPIOS1", vmbase, text_size, data_vmaddr, data_vmsize, data_filesize,
          n_rebase, n_bind, n_init, n_names, off_text, off_data, off_rebase, off_bind, off_init, off_names, (16 x u32 spare)
  text    __TEXT bytes (vmbase .. vmbase+text_size)
  data    __DATA file bytes (data_filesize; the rest of data_vmsize is zero)
  rebase  u32 vm address of each pointer to slide
  bind    {u32 vm address, u32 name index, s32 addend, u32 kind (0 non-lazy, 1 lazy)} (weak binds of symbols the image defines
          itself are dropped: the slot already points at the image's own definition)
  init    u32 vm address of each C++ static initializer (__mod_init_func, in order)
  names   NUL-terminated import names, index order

Imports header: one line per import `X(index, "name", kind)`, kind 'F' = called through a stub (lazy), 'N' = non-lazy pointer.
"""
import struct
import sys

sys.path.insert(0, __import__("os").path.dirname(__import__("os").path.abspath(__file__)))
from macho import MachO  # noqa: E402


def main():
    src, out_img, out_hdr = sys.argv[1:4]
    m = MachO(src)
    text = next(s for s in m.segments if s["name"] == "__TEXT")
    data = next(s for s in m.segments if s["name"] == "__DATA")
    assert text["vmaddr"] + text["vmsize"] == data["vmaddr"], "TEXT and DATA must be adjacent"
    tbytes = m.d[text["fileoff"]:text["fileoff"] + text["filesize"]]
    tbytes += b"\0" * (text["vmsize"] - len(tbytes))
    dbytes = m.d[data["fileoff"]:data["fileoff"] + data["filesize"]]
    lo, hi = text["vmaddr"], data["vmaddr"] + data["vmsize"]

    reb = [a for a, t in m.rebases()]
    assert all(lo <= a < hi for a in reb)
    # symbols the image defines itself (weak C++ template instances are still reached through stubs / binds): address with the
    # Thumb bit (nlist N_ARM_THUMB_DEF = n_desc 0x0008); the export trie wins where both exist
    own = {}
    for name, nt, ns, nd, nv in m.symbols:
        if (nt & 0x0E) == 0x0E:
            own[name] = nv | (1 if nd & 0x0008 else 0)
    own.update(m.exports())
    patch = {}                      # vm address of a slot -> value to store (an own address; the slot is then slid like a rebase)
    names, index, binds, kinds = [], {}, [], {}
    dropped = 0
    for addr, lib, name, addend, typ, flags, kind in m.binds():
        if name in own:
            patch[addr] = (own[name] + addend) & 0xFFFFFFFF
            dropped += 1
            continue
        if name not in index:
            index[name] = len(names)
            names.append(name)
        k = 1 if kind == "lazy" else 0
        kinds[name] = "F" if k or kinds.get(name) == "F" else "N"
        binds.append((addr, index[name], addend, k))
    # resolve the self-binds in the image bytes and slide them like the other internal pointers
    dbytes = bytearray(dbytes)
    tbytes = bytearray(tbytes)
    for a, v in patch.items():
        if data["vmaddr"] <= a < data["vmaddr"] + len(dbytes):
            struct.pack_into("<I", dbytes, a - data["vmaddr"], v)
        elif lo <= a < data["vmaddr"]:
            struct.pack_into("<I", tbytes, a - lo, v)
        else:
            raise SystemExit(f"self-bind slot {a:#x} outside the file part of the image")
        if a not in set(reb):
            reb.append(a)
    reb = sorted(set(reb))
    dbytes, tbytes = bytes(dbytes), bytes(tbytes)
    init_sec = m.section("__DATA", "__mod_init_func")
    inits = [m.u32(init_sec["addr"] + 4 * i) for i in range(init_sec["size"] // 4)] if init_sec else []

    blob_names = b"".join(n.encode() + b"\0" for n in names)
    hdr_size = 8 + 16 * 4 + 16 * 4
    off_text = hdr_size
    off_data = off_text + len(tbytes)
    off_reb = off_data + len(dbytes)
    off_bind = off_reb + 4 * len(reb)
    off_init = off_bind + 16 * len(binds)
    off_names = off_init + 4 * len(inits)
    hdr = b"DNMPIOS1" + struct.pack("<16I", text["vmaddr"], text["vmsize"], data["vmaddr"], data["vmsize"], len(dbytes),
                                    len(reb), len(binds), len(inits), len(names),
                                    off_text, off_data, off_reb, off_bind, off_init, off_names, 0) + b"\0" * 64
    with open(out_img, "wb") as f:
        f.write(hdr + tbytes + dbytes)
        f.write(struct.pack(f"<{len(reb)}I", *reb))
        for b in binds:
            f.write(struct.pack("<IIiI", *b))
        f.write(struct.pack(f"<{len(inits)}I", *inits))
        f.write(blob_names)
    with open(out_hdr, "w") as f:
        f.write("/* generated by ios/tools/prelink.py - imports of the iOS binary: X(index, name, kind) */\n")
        for i, n in enumerate(names):
            f.write(f'X({i}, "{n}", \'{kinds[n]}\')\n')
    print(f"image {out_img}: text {len(tbytes):#x} data {len(dbytes):#x}/{data['vmsize']:#x}, {len(reb)} rebases, "
          f"{len(binds)} binds to imports ({dropped} self-binds resolved in the image), {len(names)} imports, {len(inits)} initializers")


if __name__ == "__main__":
    main()
